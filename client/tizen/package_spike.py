"""Build an unsigned GhostpadSpike.wgt from client/tizen/spike/ with the PC address baked in.

The package is unsigned: install it with a tool that signs with your Samsung certificate
(Apps2Samsung "Select WGT", or `tizen package -t wgt -s <profile>` on the unzipped folder).
Signing material in the spike folder is never packaged. See docs/tizen-spike.md.

    python client/tizen/package_spike.py --pc-host 192.168.1.100
"""

from __future__ import annotations

import argparse
import ipaddress
import json
import re
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SPIKE = HERE / "spike"
DEFAULT_OUT = HERE / "GhostpadSpike.wgt"  # git-ignored (*.wgt)
CONFIG_JS = "local-config.js"
# Never packaged: signing output, certificates, editor/OS clutter.
EXCLUDE_NAMES = {"author-signature.xml", "signature1.xml", ".manifest.tmp", "Thumbs.db", ".DS_Store"}
EXCLUDE_SUFFIXES = {".p12", ".wgt"}
_HOSTNAME = re.compile(r"^[A-Za-z0-9]([A-Za-z0-9-]{0,62}[A-Za-z0-9])?(\.[A-Za-z0-9]([A-Za-z0-9-]{0,62}[A-Za-z0-9])?)*$")


def valid_host(host: str) -> bool:
    if not host:
        return True  # disables the WebSocket test
    try:
        ipaddress.ip_address(host)
        return True
    except ValueError:
        return bool(_HOSTNAME.match(host))


def config_js(host: str, port: int, token: str) -> str:
    cfg = json.dumps({"pcHost": host, "pcPort": port, "token": token})
    return f"// Generated by package_spike.py\nwindow.GHOSTPAD_SPIKE_CONFIG = {cfg};\n"


def spike_files(root: Path = SPIKE) -> list[Path]:
    """Files to package, config.xml first; skips dotfiles/dirs and signing material."""
    out = []
    for p in sorted(root.rglob("*")):
        rel = p.relative_to(root)
        if not p.is_file() or any(part.startswith(".") for part in rel.parts):
            continue
        if p.name in EXCLUDE_NAMES or p.suffix.lower() in EXCLUDE_SUFFIXES:
            continue
        out.append(p)
    out.sort(key=lambda p: (p.name != "config.xml", p.relative_to(root).as_posix()))
    return out


def build(out: Path, host: str, port: int, token: str, root: Path = SPIKE) -> list[str]:
    files = spike_files(root)
    if not files or files[0].name != "config.xml":
        raise SystemExit(f"no config.xml in {root}")
    names = []
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for p in files:
            name = p.relative_to(root).as_posix()
            if name == CONFIG_JS:
                z.writestr(name, config_js(host, port, token))
            else:
                z.write(p, name)
            names.append(name)
        if CONFIG_JS not in names:
            z.writestr(CONFIG_JS, config_js(host, port, token))
            names.append(CONFIG_JS)
    return names


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--pc-host", default="", help="PC LAN IP or hostname running the daemon (empty: no WebSocket)")
    ap.add_argument("--pc-port", type=int, default=47800)
    ap.add_argument("--token", default="", help="daemon --token, if set (stored in the package in plain text)")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args(argv)
    if not valid_host(args.pc_host):
        ap.error(f"--pc-host {args.pc_host!r} is not an IP address or hostname")
    if not 0 < args.pc_port < 65536:
        ap.error("--pc-port out of range")
    names = build(args.out, args.pc_host, args.pc_port, args.token)
    print(f"wrote {args.out} ({args.out.stat().st_size} bytes, unsigned): {' '.join(names)}")
    print(f"WebSocket: {'ws://' + args.pc_host + ':' + str(args.pc_port) + '/ws' if args.pc_host else 'disabled'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
